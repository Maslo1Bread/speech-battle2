def persona_prompt(scenario: dict) -> str:
    """Кто говорит и как — как живой оппонент по теме сценария, не шаблон."""
    sid = scenario.get("id") or ""
    if sid == "salary":
        return (
            "Ты руководитель отдела на личном разговоре с сотрудником про зарплату. "
            "Слышишь человека, объясняешь фонд и вилку своими словами, предлагаешь ступеньку, "
            "премию, грейд или дату пересмотра. Не повторяй одну и ту же фразу."
        )
    if sid == "client-discount":
        return (
            "Ты клиент, который закупает услугу. Напротив — продавец подрядчика. "
            "Бюджет срезали, конкурент дешевле примерно на 18%, тебе нужна скидка около 20% "
            "или тот же эффект в бонусах, рассрочке, поддержке. "
            "Говори как живой закупщик: хочешь закрыть контракт, но текущую цену внутри не защитишь. "
            "Если продавец спрашивает, что ты хочешь — назови скидку, срок старта или пакет, не путайся, кто ты."
        )
    if sid == "vendor-contract":
        return (
            "Ты менеджер поставщика, который ведёт этот заказ. "
            "Стандарт производства: около 21 дня и предоплата 70%. Закупщик давит на 12 дней и 40% аванса. "
            "Говори как живой человек с производства и кассы: слоты, сверхурочные, кассовый разрыв, очередь. "
            "Можно торговаться: срок взамен аванса, штраф только за вашу вину, частичная отгрузка. "
            "Отвечай на то, что сказал закупщик (срок, предоплата, штраф, объём), а не одной заученной фразой."
        )
    role = scenario.get("opponent_role") or "коллега"
    return f"Ты {role.lower()} и решаешь рабочий вопрос на встрече, как живой человек."


def _salary_reply(difficulty: str, user_text: str) -> str:
    text = (user_text or "").lower()
    other_offer = any(w in text for w in ("оффер", "предложени", "друг", "увол", "уйд", "конкурент"))
    percent = any(w in text for w in ("процент", "%", "десят", "пятнадцат", "двадцат", "повыш", "оклад"))
    effort = any(w in text for w in ("усерд", "больше работ", "результат", "проект"))

    if difficulty == "easy":
        if other_offer:
            return (
                "Ой, давайте без ультиматумов. Я вас слышу: рынок правда шевелится. "
                "Давайте хотя бы зафиксируем пересмотр через пару месяцев — я не хочу, чтобы вы уходили из-за цифры."
            )
        if percent:
            return (
                "Понимаю, что хочется прибавки. Фонд уже сверстан, но давайте не рубить сплеча: "
                "могу согласовать небольшую корректировку и отдельный разговор по вилке ближе к следующему кварталу."
            )
        return (
            "Хорошо, давайте спокойно. Я ценю, что вы пришли поговорить, а не ставили перед фактом. "
            "Расскажите, какая сумма для вас комфортна, и посмотрим, что реально протянуть через бюджет."
        )

    if difficulty == "hard":
        if other_offer:
            return (
                "Рыночный оффер — это ориентир, не обязательство компании. "
                "Сейчас ФОТ закрыт, 10% сразу я не подпишу. Если остаётесь, давайте говорить про грейд, KPI "
                "и дату пересмотра. Если это ультиматум — мне нужно время на замену, и это уже другой разговор."
            )
        if effort:
            return (
                "Старание само по себе бюджет не открывает. Мне нужны измеримые итоги по двум проектам: "
                "эффект, сроки, что берёте на следующий квартал. Без этого вынести повышение я не смогу."
            )
        return (
            "Давайте предметно. Вилка по роли сейчас не тянет плюс 10% без пересмотра грейда. "
            "Могу вынести 4–6% или пакет: премия плюс пересмотр через три месяца при цифрах. Что выбираете?"
        )

    if other_offer:
        return (
            "Понимаю, что другое предложение давит. Я не хочу вас терять, но и ломать утверждённый фонд не буду. "
            "Давайте сойдёмся так: фиксируем пересмотр через три месяца и смотрим, какую часть прибавки "
            "можно закрыть премией или грейдом уже сейчас."
        )
    if percent:
        return (
            "Десять процентов сразу — тяжело: квартальный фонд уже утверждён. "
            "Я готов обсуждать ступеньку меньше и дату, когда вернёмся к полной цифре. "
            "Чем именно вы подкрепляете запрос — проектами или рыночной вилкой?"
        )
    return (
        "Я вас слышу. Давайте разберём по-человечески: что для вас критично прямо сейчас — "
        "цифра в окладе, срок пересмотра или дополнительные обязанности с доплатой? "
        "От этого зависит, что я смогу согласовать."
    )


def _discount_reply(difficulty: str, user_text: str) -> str:
    text = (user_text or "").lower()
    competitor = any(w in text for w in ("конкурент", "друг", "подрядчик", "рынок", "18"))
    value = any(w in text for w in ("бонус", "поддерж", "пакет", "час", "обучен", "внедрен", "рассроч"))
    small = any(w in text for w in ("8%", "восемь", "марж", "рентаб", "не можем", "максимум 5", "максимум 8"))
    percent = any(w in text for w in ("скидк", "процент", "%", "дешев", "цен", "двадцат", "десят"))

    if difficulty == "easy":
        if value:
            return (
                "Бонусы — это хорошо, я такое люблю доносить руководству. "
                "Давайте тогда явно запишем, что входит в пакет, и я смогу чуть уступить по чистой скидке. "
                "Мне главное — не выйти за урезанный бюджет."
            )
        if small:
            return (
                "Восемь процентов мне будет тяжело защитить, коллеги уже видели более жирные цифры. "
                "Но если старт быстрый и вы зафиксируете цену на год, я попробую согласовать середину. "
                "Какую ступеньку реально протянуть, чтобы вам не резало маржу?"
            )
        if percent or competitor:
            return (
                "Я не хочу торговаться до ночи. Бюджет срезали, и мне нужно либо ближе к двадцати процентам, "
                "либо понятный обмен — рассрочка, доп.часы, быстрый запуск. "
                "Если сойдёмся, я готов подписать на этой неделе и не ходить по рынку."
            )
        return (
            "Давайте по-человечески: контракт мне нужен, люди ждут старт. "
            "Скажите, где у вас вообще есть люфт — в цене, в объёме или в условиях оплаты? "
            "От этого я пойму, что могу унести на согласование."
        )

    if difficulty == "hard":
        if value and not percent:
            return (
                "Пакет не заменяет минус восемнадцать у конкурента, если в деньгах дыра остаётся. "
                "Либо выходите к двадцати процентам, либо режьте объём и дайте SLA и внедрение в ту же сумму. "
                "Иначе я на комитете это не проведу."
            )
        if small:
            return (
                "Восемь процентов при нашей вилке — это отказ, давайте не тратить время. "
                "Конкурент уже прислал оферту минус восемнадцать. Что закрываете сегодня, чтобы я не ушёл?"
            )
        if competitor or percent:
            return (
                "Цифры простые: мне нужна скидка около 20% или эквивалент, который я покажу в таблице сравнения. "
                "Без этого я подписываю у другого подрядчика на этой неделе. "
                "Какой конкретный оффер оставляете на столе?"
            )
        return (
            "Мне не нужна вода про партнёрство. Либо цена ближе к рынку, либо в контракт идут часы поддержки "
            "и старт без ожидания. Иначе закупка закрывается не у вас."
        )

    if value:
        return (
            "Доп.опции я готов считать, если они реально экономят мне людей и время. "
            "Давайте тогда так: часть скидки плюс фиксированный пакет поддержки, чтобы я мог защитить сделку внутри. "
            "Без этого 20% всё равно висят как целевая цифра."
        )
    if small:
        return (
            "Понимаю, что маржа у вас тонкая. Мне тоже бюджет срезали, и восемь процентов — это не то, "
            "с чем меня отпустили. Давайте середину: чуть больше скидки и явный бонус, который я внесу в обоснование."
        )
    if percent or competitor:
        return (
            "Я не торгуюсь ради спорта: конкурент уже дал заметно ниже, а меня отпустили с цифрой около 20%. "
            "Если полную скидку не тянете, закройте часть цены плюс рассрочку или быстрый старт — "
            "иначе мне нечем идти на внутреннее согласование."
        )
    return (
        "Мы почти готовы, но текущая цена у меня не проходит. "
        "Давайте найдём схему, которую я смогу защитить: скидка, график платежей или дополнительные опции "
        "в той же сумме. Что вам проще отдать?"
    )


def _vendor_reply(difficulty: str, user_text: str) -> str:
    text = (user_text or "").lower()
    rush = any(
        w in text
        for w in ("срок", "быстр", "12", "двенадцат", "недел", "дней", "дедлайн", "запуск", "срыв")
    )
    prepay = any(w in text for w in ("предоплат", "аванс", "оплат", "40", "70", "сорок", "семьдесят", "касс"))
    penalty = any(w in text for w in ("штраф", "неустойк", "ответствен", "просроч", "гарант"))
    volume = any(w in text for w in ("объём", "парти", "повтор", "долг", "контракт на год"))

    if difficulty == "easy":
        if penalty:
            return (
                "Штраф я понимаю, вам нужна страховка. Давайте пропишем ответственность за нашу просрочку, "
                "но без космических сумм — иначе производство просто не возьмёт заказ. "
                "Срок при этом можем чуть сжать, если подтверждаете сегодня."
            )
        if prepay and rush:
            return (
                "И двенадцать дней, и сорок процентов аванса сразу — нам будет тяжело по кассе. "
                "Но заказ интересный. Давайте так: срок ближе к двум неделям, предоплату чуть опустим "
                "от семидесяти, если вы фиксируете объём. Пойдёт?"
            )
        if prepay:
            return (
                "Семидесяти процентов бухгалтерия просит не из вредности — комплектующие сами покупаем вперёд. "
                "Могу обсудить ступеньку вниз, если часть суммы закрываем по отгрузке. "
                "Какой график оплаты вам реально удобен?"
            )
        if rush:
            return (
                "Дедлайн слышу, правда не из вредности держимся за 21 день — это очередь на линии. "
                "Если подтверждаете заказ сегодня, попробую подвинуть вас вперёд и ужать срок. "
                "На сколько дней вам критично попасть, чтобы запуск не сорвался?"
            )
        return (
            "Давайте спокойно разберём. Нам важен заказ, вам — срок и живые деньги. "
            "Скажите, что больнее: ждать три недели или платить большой аванс? "
            "От этого я пойму, где могу уступить без срыва производства."
        )

    if difficulty == "hard":
        if penalty and (rush or prepay):
            return (
                "Двенадцать дней, сорок процентов и ещё штраф за любую задержку — это работа в минус. "
                "Могу 14–16 дней при 60% предоплаты и неустойке только за нашу вину, не за логистику клиента. "
                "Иначе партию не ставлю в график."
            )
        if prepay or rush:
            return (
                "Производство не резиновое: 12 дней и 40% аванса сразу кассу рвут. "
                "Либо оставляете ближе к 21 дню и 70%, либо платите за слот и сверхурочные. "
                "Какой обмен фиксируем, чтобы я не подставлял цех?"
            )
        if penalty:
            return (
                "Штраф за всё подряд я не подпишу — тогда мне проще отказаться от заказа. "
                "Готов неустойку за нашу просрочку по вине цеха, с потолком. "
                "Без потолка и без вины сторон контракта не будет."
            )
        return (
            "Я не обещаю то, что линия не вытянет. Давайте реалистичный срок, аванс и ответственность. "
            "Без этого я документ не подпишу — потом разбирать срыв дороже, чем потерять этот заказ."
        )

    if penalty:
        return (
            "Неустойку могу принять, если она привязана к нашей вине и не съедает всю маржу. "
            "Давайте тогда обмен: вы чуть двигаетесь по предоплате или сроку — я фиксирую штраф с потолком. "
            "Так обе стороны остаются при живых деньгах."
        )
    if prepay and rush:
        return (
            "Сжать и срок, и аванс одновременно — кассовый разрыв. "
            "Могу ускорить поставку, если предоплата останется ближе к нашей норме, "
            "или опустить аванс, если оставляете стандартные 21 день. Что для вас больнее отдать?"
        )
    if rush:
        return (
            "Ускорение возможно, но не бесплатно: сдвигаем слот и сверхурочные. "
            "Если двенадцать дней критичны, давайте обмен — чуть выше предоплата, и я двигаю вас вперёд очереди. "
            "Иначе честно останемся около трёх недель."
        )
    if prepay:
        return (
            "Сорок процентов аванса нам слабо закрывает закупку комплектующих. "
            "Давайте график: больше на старте, остаток по отгрузке, и я уже смогу говорить про срок ближе к вашему дедлайну. "
            "Какую сумму готовы провести сразу?"
        )
    if volume:
        return (
            "Если это не разовая партия, а повтор, мне проще выбить у производства живой слот. "
            "Зафиксируйте объём на квартал — обсудим и срок, и предоплату мягче. "
            "Без объёма остаёмся на стандарте 21 день и 70%."
        )
    return (
        "Заказ нам интересен, но кассу и линию я тоже не могу подставить. "
        "Давайте сойдёмся на сроке ближе к вашему запуску и предоплате, которую пропустит бухгалтерия. "
        "С чего начнём — с дней или с денег?"
    )


def _used_ai_texts(history: list[dict] | None) -> set[str]:
    return {(item.get("content") or "").strip() for item in (history or []) if item.get("sender_type") == "ai"}


def _next_unused(history: list[dict] | None, lines: list[str]) -> str:
    used = _used_ai_texts(history)
    for line in lines:
        if line not in used:
            return line
    turn = sum(1 for item in (history or []) if item.get("sender_type") == "ai")
    return lines[turn % len(lines)]


