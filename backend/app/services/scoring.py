def local_ai_reply(scenario: dict, difficulty: str, history: list[dict], user_text: str) -> str:
    """Запасной ответчик: живая речь в роли оппонента, без повтора одной и той же фразы."""
    sid = scenario.get("id") or ""
    if sid == "salary":
        reply = _salary_reply(difficulty, user_text)
        pool = _SALARY_FOLLOWUPS
    elif sid == "client-discount":
        reply = _discount_reply(difficulty, user_text)
        pool = _DISCOUNT_FOLLOWUPS
    elif sid == "vendor-contract":
        reply = _vendor_reply(difficulty, user_text)
        pool = _VENDOR_FOLLOWUPS
    else:
        role = scenario.get("opponent_role") or "коллега"
        return (
            f"Давайте по существу. Я здесь как {role.lower()} и хочу закрыть вопрос, а не спорить ради спора. "
            "Что для вас сейчас главное — цифра, срок или условия? От этого оттолкнёмся."
        )
    if reply not in _used_ai_texts(history):
        return reply
    return _next_unused(history, pool)
